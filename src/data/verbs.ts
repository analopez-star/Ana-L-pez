// Helpers for regular French verb patterns
function frEr(stem: string, eStem?: string): VerbDefinition['fr'] {
  const s = eStem ?? stem;
  return {
    present: [`${stem}e`, `${stem}es`, `${stem}e`, `${stem}ons`, `${stem}ez`, `${stem}ent`],
    imparfait: [`${stem}ais`, `${stem}ais`, `${stem}ait`, `${stem}ions`, `${stem}iez`, `${stem}aient`],
    futur_simple: [`${s}erai`, `${s}eras`, `${s}era`, `${s}erons`, `${s}erez`, `${s}eront`],
    conditionnel_present: [`${s}erais`, `${s}erais`, `${s}erait`, `${s}erions`, `${s}eriez`, `${s}eraient`],
    subjonctif_present: [`${stem}e`, `${stem}es`, `${stem}e`, `${stem}ions`, `${stem}iez`, `${stem}ent`],
    imperatif: [`${stem}e`, `${stem}ons`, `${stem}ez`],
  };
}

function frIr2(stem: string): VerbDefinition['fr'] {
  return {
    present: [`${stem}is`, `${stem}is`, `${stem}it`, `${stem}issons`, `${stem}issez`, `${stem}issent`],
    imparfait: [`${stem}issais`, `${stem}issais`, `${stem}issait`, `${stem}issions`, `${stem}issiez`, `${stem}issaient`],
    futur_simple: [`${stem}irai`, `${stem}iras`, `${stem}ira`, `${stem}irons`, `${stem}irez`, `${stem}iront`],
    conditionnel_present: [`${stem}irais`, `${stem}irais`, `${stem}irait`, `${stem}irions`, `${stem}iriez`, `${stem}iraient`],
    subjonctif_present: [`${stem}isse`, `${stem}isses`, `${stem}isse`, `${stem}issions`, `${stem}issiez`, `${stem}issent`],
    imperatif: [`${stem}is`, `${stem}issons`, `${stem}issez`],
  };
}

function frFutur(stem: string): string[] {
  return [`${stem}ai`, `${stem}as`, `${stem}a`, `${stem}ons`, `${stem}ez`, `${stem}ont`];
}

function frCond(stem: string): string[] {
  return [`${stem}ais`, `${stem}ais`, `${stem}ait`, `${stem}ions`, `${stem}iez`, `${stem}aient`];
}

function frImp(stem: string): string[] {
  return [`${stem}ais`, `${stem}ais`, `${stem}ait`, `${stem}ions`, `${stem}iez`, `${stem}aient`];
}

// Helpers for Spanish compound tenses from past participle
const ES_HABER_PRES = ['he', 'has', 'ha', 'hemos', 'habéis', 'han'];
const ES_HABER_IMP = ['había', 'habías', 'había', 'habíamos', 'habíais', 'habían'];
const ES_HABER_FUT = ['habré', 'habrás', 'habrá', 'habremos', 'habréis', 'habrán'];
const ES_HABER_COND = ['habría', 'habrías', 'habría', 'habríamos', 'habríais', 'habrían'];

function esCompound(aux: string[], pp: string): string[] {
  return aux.map((a) => `${a} ${pp}`);
}

function esRegAr(stem: string, pp?: string): VerbDefinition['es'] {
  const part = pp ?? `${stem}ado`;
  return {
    present: [`${stem}o`, `${stem}as`, `${stem}a`, `${stem}amos`, `${stem}áis`, `${stem}an`],
    passe_simple: [`${stem}é`, `${stem}aste`, `${stem}ó`, `${stem}amos`, `${stem}asteis`, `${stem}aron`],
    passe_compose: esCompound(ES_HABER_PRES, part),
    imparfait: [`${stem}aba`, `${stem}abas`, `${stem}aba`, `${stem}ábamos`, `${stem}abais`, `${stem}aban`],
    plus_que_parfait: esCompound(ES_HABER_IMP, part),
    futur_simple: [`${stem}aré`, `${stem}arás`, `${stem}ará`, `${stem}aremos`, `${stem}aréis`, `${stem}arán`],
    futur_anterieur: esCompound(ES_HABER_FUT, part),
    conditionnel_present: [`${stem}aría`, `${stem}arías`, `${stem}aría`, `${stem}aríamos`, `${stem}aríais`, `${stem}arían`],
    conditionnel_passe: esCompound(ES_HABER_COND, part),
    subjonctif_present: [`${stem}e`, `${stem}es`, `${stem}e`, `${stem}emos`, `${stem}éis`, `${stem}en`],
    imperatif: [`${stem}a`, `${stem}emos`, `${stem}ad`],
  };
}

